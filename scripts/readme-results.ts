// Rewrites the delimited eval-results block in README.md from evals/results/latest.json.
// Usage: pnpm exec tsx scripts/readme-results.ts [--check]
//   (no flag)  rewrite the block in place
//   --check    exit 1 if the block is stale (the vitest test does the same check)
// Numbers are copied from latest.json, never typed by hand. All results are FIXTURE results.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const START = "<!-- eval-results:start -->";
export const END = "<!-- eval-results:end -->";

type Latest = Record<string, unknown>;

function num(o: Latest, key: string): number {
  const v = o[key];
  if (typeof v !== "number") throw new Error(`latest.json: ${key} is not a number`);
  return v;
}

function pct(n: number): string {
  return `${(n * 100).toFixed(1)}%`;
}

function obj(o: Latest, key: string): Latest {
  const v = o[key];
  if (!v || typeof v !== "object") throw new Error(`latest.json: ${key} is missing`);
  return v as Latest;
}

/** Pure: latest.json content -> markdown block (without the delimiters). */
export function renderResultsBlock(latest: Latest): string {
  const kl = obj(latest, "knownLimitations");
  const sj = obj(latest, "summaryJudge");
  const hall = obj(sj, "hallucination");
  const omis = obj(sj, "omission");
  const live = latest.liveModelRun === true ? "yes" : "no";
  const rows: [string, string][] = [
    ["Run mode", `${String(latest.mode)} (fixtures: ${String(latest.fixtureKind)})`],
    ["Live model run", live],
    ["Cases", `${num(latest, "totalCases")}`],
    ["Risk cases", `${num(latest, "riskCases")}`],
    ["Cases that exercise the AI path", `${num(latest, "aiCases")}`],
    ["Cases labelled ESCALATE", `${num(latest, "escalationCases")}`],
    ["Escalation recall (gated set)", pct(num(latest, "escalationRecall"))],
    ["Unsafe approvals", `${num(latest, "unsafeApprovals")}`],
    ["Auto-approve precision", pct(num(latest, "autoApprovePrecision"))],
    ["Outcome accuracy", pct(num(latest, "outcomeAccuracy"))],
    ["Reason-code accuracy", pct(num(latest, "reasonCodeAccuracy"))],
    ["Citation validity", pct(num(latest, "citationValidity"))],
    [
      "AI-blocked cases / LLM calls on them",
      `${num(latest, "blockedAiCases")} / ${num(latest, "llmCallsOnBlocked")}`,
    ],
    ["Known-limitation probes (not gated)", `${num(kl, "count")} probes the system still misses`],
    [
      "Escalation recall including the probes",
      `${pct(num(kl, "escalationRecallIncludingKnownLimitations"))} ` +
        `(${num(kl, "specLabelledEscalationsMissed")} missed of ${num(kl, "specLabelledEscalations")} SPEC-labelled escalations)`,
    ],
    [
      "Summary judge (fixture judgments)",
      `${num(sj, "cases")} cases, ${num(sj, "judged")} judged, ${num(sj, "judgeFailed")} fail-closed; ` +
        `hallucinations ${num(hall, "major")} major / ${num(hall, "minor")} minor, ` +
        `omissions ${num(omis, "major")} major / ${num(omis, "minor")} minor`,
    ],
    ["Gate", String(latest.gate)],
  ];
  const w = Math.max(...rows.map(([k]) => k.length));
  const v = Math.max(...rows.map(([, x]) => x.length));
  const line = (a: string, b: string) => `| ${a.padEnd(w)} | ${b.padEnd(v)} |`;
  return [
    line("Metric", "Value"),
    `| ${"-".repeat(w)} | ${"-".repeat(v)} |`,
    ...rows.map(([a, b]) => line(a, b)),
    "",
    `Source: \`evals/results/latest.json\` (generated by \`${String(latest.generatedBy)}\`). ` +
      "These are FIXTURE results: every model answer is a hand-written canned response, no live model " +
      "or live judge has ever run, so the numbers show how the pipeline handles those responses, not how " +
      "any real model performs. Recall of 100% is over the gated set only; the probes row is the honest figure.",
  ].join("\n");
}

/** Pure: replace the delimited block in a README string. Throws if the markers are missing. */
export function applyBlock(readme: string, block: string): string {
  const s = readme.indexOf(START);
  const e = readme.indexOf(END);
  if (s === -1 || e === -1 || e < s) throw new Error("README.md: eval-results markers not found");
  return `${readme.slice(0, s + START.length)}\n\n${block}\n${readme.slice(e)}`;
}

export function currentBlock(readme: string): string | null {
  const s = readme.indexOf(START);
  const e = readme.indexOf(END);
  if (s === -1 || e === -1 || e < s) return null;
  return readme
    .slice(s + START.length, e)
    .replace(/^\n+/, "")
    .replace(/\n$/, "");
}

const root = join(fileURLToPath(import.meta.url), "..", "..");

export function loadLatest(): Latest {
  return JSON.parse(readFileSync(join(root, "evals", "results", "latest.json"), "utf8")) as Latest;
}

function main(): void {
  const readmePath = join(root, "README.md");
  const readme = readFileSync(readmePath, "utf8");
  const next = applyBlock(readme, renderResultsBlock(loadLatest()));
  if (process.argv.includes("--check")) {
    if (next !== readme) {
      console.error(
        "README eval-results block is stale: run `pnpm exec tsx scripts/readme-results.ts`",
      );
      process.exit(1);
    }
    return;
  }
  writeFileSync(readmePath, next);
  console.log("README.md eval-results block updated from evals/results/latest.json");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
