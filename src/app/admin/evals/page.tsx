import Link from "next/link";
import { requirePageRole } from "@/infra/auth/guard";
import { failedCases, loadEvalResults, pct, type LoadedResults } from "./_lib/results";

export const dynamic = "force-dynamic";

function Card({
  id,
  label,
  value,
  note,
}: {
  id: string;
  label: string;
  value: string;
  note?: string;
}) {
  return (
    <div
      data-testid={`eval-card-${id}`}
      className="rounded border border-slate-300 p-3 dark:border-slate-700"
    >
      <dt className="text-xs uppercase tracking-wide text-slate-600 dark:text-slate-400">
        {label}
      </dt>
      <dd className="mt-1 text-xl font-semibold" data-value={value}>
        {value}
      </dd>
      {note && <p className="mt-1 text-xs text-slate-600 dark:text-slate-400">{note}</p>}
    </div>
  );
}

function ResultsBlock({
  title,
  loaded,
  testId,
}: {
  title: string;
  loaded: LoadedResults;
  testId: string;
}) {
  if (loaded.state === "missing") {
    return (
      <section data-testid={testId} data-state="missing" className="mt-8">
        <h2 className="text-lg font-semibold">{title}</h2>
        <p className="mt-2 text-sm">
          {testId === "evals-live"
            ? "No live model run has been recorded. Live evaluation needs real credentials and has not been run for this demo."
            : "No results file found. Run pnpm eval to generate evals/results/latest.json."}
        </p>
      </section>
    );
  }
  if (loaded.state === "invalid") {
    return (
      <section data-testid={testId} data-state="invalid" className="mt-8">
        <h2 className="text-lg font-semibold">{title}</h2>
        <p role="alert" className="mt-2 text-sm font-semibold text-red-800 dark:text-red-200">
          The results file could not be read as valid results ({loaded.reason}). Nothing is shown
          rather than guessing.
        </p>
      </section>
    );
  }
  const r = loaded.results;
  const failed = failedCases(r);
  const categories = Object.entries(r.byCategory).sort(([a], [b]) => a.localeCompare(b));
  return (
    <section data-testid={testId} data-state="ok" data-mode={r.mode} className="mt-8">
      <h2 className="text-lg font-semibold">{title}</h2>
      <p className="mt-2 flex flex-wrap gap-2 text-sm">
        <span data-testid="eval-mode" className="rounded border border-slate-400 px-2 py-0.5">
          Mode: {r.mode}
        </span>
        <span
          data-testid="eval-fixture-kind"
          className="rounded border border-amber-700 bg-amber-50 px-2 py-0.5 text-amber-950 dark:bg-amber-950 dark:text-amber-100"
        >
          {r.fixtureKind === null
            ? "model responses: live model"
            : `fixtures: ${r.fixtureKind} (model responses were written by hand, not produced by a real model)`}
        </span>
        <span
          data-testid="eval-live-flag"
          data-live={String(r.liveModelRun)}
          className="rounded border border-slate-400 px-2 py-0.5"
        >
          liveModelRun: {String(r.liveModelRun)}
        </span>
        <span data-testid="eval-gate" className="rounded border border-slate-400 px-2 py-0.5">
          Gate: {r.gate ?? "unknown"}
        </span>
      </p>
      <p className="mt-2 text-xs text-slate-600 dark:text-slate-400">
        Synthetic cases only. Generated by {r.generatedBy}.
      </p>

      <dl className="mt-4 grid grid-cols-2 gap-3 sm:grid-cols-4">
        <Card
          id="total"
          label="Cases"
          value={String(r.totalCases)}
          note={`${r.riskCases} risk, ${r.aiCases} through the AI stage`}
        />
        <Card
          id="escalation-recall"
          label="Escalation recall"
          value={pct(r.escalationRecall)}
          note={`${r.escalationCases} must-escalate cases`}
        />
        <Card id="unsafe-approvals" label="Unsafe approvals" value={String(r.unsafeApprovals)} />
        <Card
          id="auto-precision"
          label="Auto-approve precision"
          value={pct(r.autoApprovePrecision)}
        />
        <Card id="outcome-accuracy" label="Outcome accuracy" value={pct(r.outcomeAccuracy)} />
        <Card id="reason-accuracy" label="Reason-code accuracy" value={pct(r.reasonCodeAccuracy)} />
        <Card
          id="citation-validity"
          label="Citation validity"
          value={pct(r.citationValidity)}
          note={`${r.modelSignalsChecked} model signals checked`}
        />
        <Card id="failed" label="Failed cases" value={String(r.failedCaseIds.length)} />
      </dl>

      {r.manifestFailures && r.manifestFailures.length > 0 && (
        <p role="alert" className="mt-3 text-sm font-semibold text-red-800 dark:text-red-200">
          Manifest problems: {r.manifestFailures.join("; ")}
        </p>
      )}

      <h3 className="mt-6 font-semibold">Failed cases</h3>
      {r.failedCaseIds.length === 0 && failed.length === 0 ? (
        <p data-testid="eval-no-failures" className="mt-1 text-sm">
          No failed cases in this run.
        </p>
      ) : (
        <table data-testid="eval-failures" className="mt-2 w-full text-left text-sm">
          <thead>
            <tr>
              <th className="pr-3">Case</th>
              <th className="pr-3">Expected</th>
              <th className="pr-3">Actual</th>
            </tr>
          </thead>
          <tbody>
            {(failed.length > 0 ? failed.map((c) => c.id) : r.failedCaseIds).map((id) => {
              const c = failed.find((x) => x.id === id);
              return (
                <tr key={id} data-testid={`eval-failure-${id}`}>
                  <td className="pr-3">{id}</td>
                  <td className="pr-3">
                    {c ? `${c.expectedOutcome} [${c.expectedReasonCodes.join(", ")}]` : "n/a"}
                  </td>
                  <td className="pr-3">
                    {c ? `${c.actualOutcome} [${c.actualReasonCodes.join(", ")}]` : "n/a"}
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>
      )}

      <h3 className="mt-6 font-semibold">By category</h3>
      <table className="mt-2 w-full text-left text-sm">
        <thead>
          <tr>
            <th className="pr-3">Category</th>
            <th className="pr-3">Cases</th>
            <th className="pr-3">Failed</th>
            <th className="pr-3">Escalated / expected</th>
            <th className="pr-3">Unsafe approvals</th>
          </tr>
        </thead>
        <tbody>
          {categories.map(([name, c]) => (
            <tr key={name}>
              <td className="pr-3">
                {name}
                {c.risk ? " (risk)" : ""}
              </td>
              <td className="pr-3">{c.cases}</td>
              <td className="pr-3">{c.failed}</td>
              <td className="pr-3">
                {c.escalated} / {c.escalationCases}
              </td>
              <td className="pr-3">{c.unsafeApprovals}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </section>
  );
}

export default async function EvalsPage() {
  // Admin only, server side: other roles are redirected to /forbidden.
  await requirePageRole("admin");
  const { latest, live } = await loadEvalResults();
  return (
    <main className="mx-auto max-w-5xl px-6 py-8">
      <h1 className="text-2xl font-semibold">Eval results</h1>
      <p className="mt-1 text-sm text-slate-600 dark:text-slate-400">
        Offline evaluation of the rules and the AI risk screen on synthetic, hand-labelled cases.
        These are not clinical performance claims.
      </p>
      <p className="mt-2 text-sm">
        <Link href="/admin/dashboard" className="underline">
          Dashboard
        </Link>
      </p>
      <ResultsBlock title="Fixtures run (latest.json)" loaded={latest} testId="evals-latest" />
      <ResultsBlock title="Live model run (live-latest.json)" loaded={live} testId="evals-live" />
    </main>
  );
}
